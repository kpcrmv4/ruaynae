--
-- เดิม exclusion constraint กัน "คนเดียวกัน ช่วงเวลาซ้อนกัน" **ข้ามทุกโครงการ** —
-- อาการที่เจ้าของเห็น: มอบหมายคนที่ดูแลโครงการ A อยู่ให้โครงการ B ด้วย แล้วขึ้น
-- "ช่วงเวลาทับกับโครงการอื่นที่คนนี้ดูแลอยู่" ทั้งที่งานจริงคนหนึ่งดูแลหลายที่เป็นเรื่องปกติ
--
-- 🔴 ที่ต้องกันจริง ๆ คือ **คนเดียวกัน โครงการเดียวกัน ช่วงเวลาซ้อนกัน** — สองแถว
-- ที่บอกว่าสมชายดูแลโครงการ A ในวันเดียวกัน คือข้อมูลซ้ำที่ทำให้ `supervises_site()`
-- และรายงานนับสองเท่า · จึงเพิ่ม `site_id` เข้าไปในเงื่อนไข ไม่ใช่ถอดออกทั้งก้อน
--
-- 🔴 `effective_to + 1` และ `'[)'` คงไว้เหมือนเดิม (ปลายทางแบบรวมวัน — ดู p1_sites)
-- · ไม่แตะ `supervises_site()` เลย มันเช็คว่า "มีแถวของคนนี้ที่โครงการนี้ครอบวันนั้นไหม"
--   ซึ่งถูกอยู่แล้วไม่ว่าคนนั้นจะมีกี่โครงการ
alter table public.site_supervisors drop constraint if exists site_supervisors_no_overlap;
alter table public.site_supervisors add constraint site_supervisors_no_overlap
  exclude using gist (
    site_id with =,
    profile_id with =,
    daterange(effective_from, effective_to + 1, '[)') with &&
  );
