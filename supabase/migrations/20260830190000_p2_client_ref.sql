-- ทุกกรณีนั้นจบด้วย **รายจ่ายสองแถวที่เหมือนกันทุกอย่าง** ซึ่งเป็นเงินที่ถูกนับซ้ำ
-- และไม่มีใครรู้ว่าซ้ำเพราะรายจ่ายชื่อเดียวกันวันเดียวกันก็เกิดขึ้นได้จริง
--
-- client สร้าง uuid หนึ่งค่าต่อ "หนึ่งครั้งที่ตั้งใจบันทึก" แล้วส่งมาด้วย
-- ยิงซ้ำด้วยค่าเดิม = ชน unique index = ฐานข้อมูลปฏิเสธแถวที่สอง
alter table public.transactions
  add column if not exists client_ref uuid;

create unique index if not exists transactions_client_ref_uniq
  on public.transactions(client_ref)
  where client_ref is not null;
