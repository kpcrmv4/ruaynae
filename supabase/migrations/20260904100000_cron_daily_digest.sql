-- ตั้งงาน `daily-digest` และเลื่อน `recurring-expenses` ขึ้นก่อนหน้าเล็กน้อย
-- ════════════════════════════════════════════════════════════════════════
--
-- 🔴 pg_cron เป็น **UTC** — 8 โมงเช้าไทยคือ `0 1 * * *`
--
-- ลำดับตั้งใจให้เป็นแบบนี้: ลงรายจ่ายรายเดือนของวัน (07:55) → แล้วค่อยสรุป
-- ของค้างส่งเจ้าของ (08:00) · สรุปที่ส่งก่อนรายการของวันถูกลงคือสรุปที่
-- ล้าไปหนึ่งรอบทุกวันที่ 1 ของเดือน โดยไม่มีอะไรบอกว่าทำไมตัวเลขไม่ตรง

select cron.schedule(
  'recurring-expenses',
  '55 0 * * *',                      -- 07:55 เวลาไทย
  $$select public.cron_call('/api/cron/recurring')$$
);

select cron.schedule(
  'daily-digest',
  '0 1 * * *',                       -- 08:00 เวลาไทย
  $$select public.cron_call('/api/cron/daily-digest')$$
);
