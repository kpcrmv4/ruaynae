alter type public.notification_kind add value if not exists 'daily_digest';

-- ── กันส่งซ้ำวันเดียวกัน ────────────────────────────────────────────
-- 🔴 cron อาจถูกเรียกซ้ำ (ลองด้วยมือ · เครือข่ายสะดุดแล้ว pg_net ยิงใหม่ ·
-- คนกดทดสอบ) — ตัวกันต้องอยู่ที่ฐานข้อมูล ไม่ใช่ความหวังว่าจะถูกเรียกวันละครั้ง
--
-- ⚠️ วันต้องเป็น **วันไทย** และคำนวณฝั่งแอป ไม่ใช่ `now()::date` ที่นี่ —
-- เซิร์ฟเวอร์เป็น UTC ตอนตีห้าของไทยยังเป็นเมื่อวานในสายตาฐานข้อมูล
alter table public.notifications
  add column if not exists digest_date date;

comment on column public.notifications.digest_date is
  'วันไทยของสรุปประจำวัน (เฉพาะ kind = daily_digest) — คีย์กันส่งซ้ำวันเดียวกัน';

create unique index if not exists notifications_digest_once
  on public.notifications(user_id, digest_date)
  where digest_date is not null;
